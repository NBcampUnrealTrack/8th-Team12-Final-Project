const FGuid& USMGraphK2Node_PropertyNode_Base::GetOwningNodeGuidChecked() const
{
	// First try safe approach. This is especially useful if the graph is being deleted, because
	// GetRuntimeNodeGuidChecked will fail.
	if (const USMPropertyGraph* PropertyGraph = GetPropertyGraph())
	{
		if (const USMGraphK2* K2Graph = Cast<USMGraphK2>(PropertyGraph->GetOuter()))
		{
			if (const FSMNode_Base* RuntimeNode = K2Graph->GetRuntimeNode())
			{
				return RuntimeNode->GetNodeGuid();
			}
		}
		else if (const USMGraph* SMGraph = Cast<USMGraph>(PropertyGraph->GetOuter()))
		{
			// State machine state nodes use USMGraph (not USMGraphK2) as their bound graph.
			if (const FSMNode_Base* RuntimeNode = SMGraph->GetRuntimeNode())
			{
				return RuntimeNode->GetNodeGuid();
			}
		}
	}
	return GetOwningGraphNodeChecked()->GetRuntimeNodeGuidChecked();
}

