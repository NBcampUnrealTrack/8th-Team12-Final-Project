void USMGraphK2Node_PropertyNode_Base::PreCompile(FSMKismetCompilerContext& CompilerContext)
{
	if (const UEdGraphSchema* Schema = GetSchema())
	{
		const TArray<UEdGraphPin*> PinsCopy = Pins;
		for (UEdGraphPin* Pin : PinsCopy)
		{
			if (!Pin || !Pin->bOrphanedPin)
			{
				continue;
			}

			UEdGraphPin* OrphanPin = Pin;
			
			// Migrate orphan input pin data (default value and wires) to the new result pin
			// when the type matches and the new pin is untouched. Recovers user work after a
			// blueprint property rename.
			if (OrphanPin->Direction == EGPD_Input)
			{
				UEdGraphPin* NewResultPin = GetResultPin(EGPD_Input);
				if (NewResultPin
					&& NewResultPin != OrphanPin
					&& !NewResultPin->bOrphanedPin
					&& NewResultPin->PinType == OrphanPin->PinType
					&& NewResultPin->LinkedTo.Num() == 0
					&& Schema->DoesDefaultValueMatchAutogenerated(*NewResultPin))
				{
					NewResultPin->MovePersistentDataFromOldPin(*OrphanPin);

					CompilerContext.MessageLog.Note(
						*FString::Printf(
							TEXT("@@ migrated pin data from renamed pin '%s' to '%s'."),
							*OrphanPin->PinName.ToString(), *NewResultPin->PinName.ToString()),
						this);
				}
			}

			// Break any invalid pin links. Helpful for directionality or type changes.
			Schema->BreakPinLinks(*OrphanPin, true);
		}
	}
	
	// Verify we have our output writer. This helps if the user changes the directionality of a variable
	// after its state was already placed in the graph. It's better to catch it here than try to rely on
	// the slate output connector, as adding nodes at that point can cause issues where the dragged pin
	// will become out-of-date.
	if (IsOutputProperty() && !IsPinWired(ESMGraphPropertyDirection::Output))
	{
		LD::Editor::PropertyUtils::IO::GetOrPlacePropertyWriterNode(this);
	}
	
	// Notify all IO nodes of pre compile.
	TArray<USMGraphK2Node_PropertyIOBase*> IONodes;
	FSMBlueprintEditorUtils::GetAllNodesOfClassNested<USMGraphK2Node_PropertyIOBase>(GetPropertyGraph(), IONodes);

	for (USMGraphK2Node_PropertyIOBase* IONode : IONodes)
	{
		IONode->PreCompile();
	}
}

void USMGraphK2Node_PropertyNode_Base::LogPropertyFromTokenizedMessage(
	const TSharedRef<FTokenizedMessage>& InTokenizedMessage)
{
	ESMLogType MessageLogType;
	switch (InTokenizedMessage->GetSeverity())
	{
	case EMessageSeverity::Info:
		{
			MessageLogType = ESMLogType::Note;
			break;
		}
	case EMessageSeverity::Warning:
		{
			MessageLogType = ESMLogType::Warning;
			break;
		}
	case EMessageSeverity::Error:
		{
			MessageLogType = ESMLogType::Error;
			break;
		}
	default:
		{
			MessageLogType = ESMLogType::Note;
			break;
		}
	}
	SetNotificationAndHighlight(true, MessageLogType, InTokenizedMessage->ToText().ToString(), true);
}

FProperty* USMGraphK2Node_PropertyNode_Base::GetProperty() const
{
	if (const USMNodeInstance* NodeTemplate = GetOwningTemplate())
	{
		if (const FSMGraphProperty_Base* GraphProperty = GetPropertyNodeConst())
		{
			return GraphProperty->MemberReference.ResolveMember<FProperty>(NodeTemplate->GetClass());
		}
	}

	return nullptr;
}

