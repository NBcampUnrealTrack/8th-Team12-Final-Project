void USMGraphK2Node_PropertyIOReaderNode::PreCompileValidate(FCompilerResultsLog& MessageLog)
{
	if (UEdGraphPin* OutPin = GetPropertyPinIn())
	{
		// Helps cases where the user changed the type of the pin.
		UpdatePropertySelectionPin(OutPin, false);
	}
	
	Super::PreCompileValidate(MessageLog);
	
	const UEdGraphPin* PropertyPin = GetPropertyPinInChecked();
	VerifyCorrectPinData(PropertyPin, MessageLog);
}

void USMGraphK2Node_PropertyIOReaderNode::CustomExpandNode(FSMKismetCompilerContext& CompilerContext,
                                                               USMGraphK2Node_RuntimeNodeContainer* RuntimeNodeContainer, FProperty* NodeProperty)
{
	using namespace LD::Editor::PropertyUtils::IO;
	
	const UEdGraphPin* OldValuePinOut = GetConnectorPinOutChecked();
	if (OldValuePinOut->LinkedTo.Num() == 0 || OldValuePinOut->bNotConnectable)
	{
		return;
	}

	const UEdGraphPin* OldPropertyPinIn = GetPropertyPinInChecked();
	if (OldPropertyPinIn->IsDefaultAsStringEmpty())
	{
		// We have no property set.
		BreakAllNodeLinks();
		return;
	}
	
	const USMGraphK2Node_PropertyIOReaderNode* SourceReaderNode =
		CastChecked<USMGraphK2Node_PropertyIOReaderNode>(CompilerContext.MessageLog.FindSourceObject(this));

	const TSharedPtr<FPropertyData_Base> PropertyData = SourceReaderNode->GetSelectedNodePropertyData();
	if (!PropertyData.IsValid() || PropertyData->Property == nullptr)
	{
		CompilerContext.MessageLog.Error(TEXT("Property not selected for @@."), this);
		return;
	}

	const UFunction* Function = USMInstance::StaticClass()->FindFunctionByName(TEXT("K2_ReadOutputProperty"));
	check(Function);
	
	UK2Node_CallFunction* ReadOutputFunctionNode = FSMBlueprintEditorUtils::CreateFunctionCall(CompilerContext.ConsolidatedEventGraph, Function);
	CompilerContext.MessageLog.NotifyIntermediateObjectCreation(ReadOutputFunctionNode, this);
	
	UEdGraphPin* FunctionPropertyPathPinIn = ReadOutputFunctionNode->FindPinChecked(FName("PropertyPath"));
	UEdGraphPin* FunctionValuePinOut = ReadOutputFunctionNode->FindPinChecked(FName("OutValue"));

	FunctionValuePinOut->PinType = OldValuePinOut->PinType;

	// Create make struct based on selected property data.
	const UK2Node_MakeStruct* MakeStructNode = MakeAndWirePropertyPathStruct(CompilerContext, PropertyData, FunctionPropertyPathPinIn);

	// PathGuid -- requires pin wire since this isn't guaranteed to be known until runtime. For readers, the property is likely
	// on another node all together, so we need to find the proper 'PathGuid' property to query at runtime.
	if (const TSharedPtr<FNodePropertyData> NodePropertyData = PropertyData->As<FNodePropertyData>())
	{
		const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
		UK2Node_StructMemberGet* GuidGetNode = CompilerContext.SpawnIntermediateNode<UK2Node_StructMemberGet>(this, CompilerContext.ConsolidatedEventGraph);

		// The source RootSMGraph.
		USMGraph* SourceRootSMGraph = FSMBlueprintEditorUtils::FindOuterRootStateMachineGraph(SourceReaderNode);
		check(SourceRootSMGraph);

		// The original node graph containing the property data we want.
		const UEdGraph* SourceNodeGraph = FSMBlueprintEditorUtils::FindGraphFromRuntimeNodeGuid(SourceRootSMGraph, NodePropertyData->NodeGuid);
		if (!SourceNodeGraph)
		{
			CompilerContext.MessageLog.Error(TEXT("Node graph not found for selected property of @@."), this);
			return;
		}

		const bool bIsNestedFSM = SourceNodeGraph->IsA<USMGraph>();
		
		const UObject* SourceNodeContainer = FSMBlueprintEditorUtils::GetRuntimeContainerFromGraph(SourceNodeGraph);
		if (!SourceNodeContainer && bIsNestedFSM)
		{
			// SMs don't have a source runtime container, but do have an intermediate one we can find from their graph.
			SourceNodeContainer = SourceNodeGraph;
		}
		if (!SourceNodeContainer)
		{
			CompilerContext.MessageLog.Error(TEXT("Node container not found for selected property of @@."), this);
			return;
		}

		// The matching compiled container node.
		const USMGraphK2Node_RuntimeNodeContainer* CompiledNodeContainer = CompilerContext.FindConsolidatedContainerFromSourceContainer(SourceNodeContainer);
		check(CompiledNodeContainer);

		// The primary container node which will have a runtime property created.
		const USMGraphK2Node_RuntimeNodeContainer* ContainerNode = CompilerContext.GetMappedContainerNodes().FindRef(
			CompiledNodeContainer->ContainerOwnerGuid);
		
		const FProperty* Property = CompilerContext.FindAllocatedNodeProperty(ContainerNode);
		if (!Property)
		{
			CompilerContext.MessageLog.Error(TEXT("Selected property of @@ could not find compiler created property of graph @@."), SourceNodeGraph, this);
			return;
		}
		
		GuidGetNode->VariableReference.SetSelfMember(Property->GetFName());
		GuidGetNode->StructType = ContainerNode->GetRunTimeNodeType();
		GuidGetNode->AllocateDefaultPins();

		// Find the property on FSMNode.
		UEdGraphPin* ValuePin = GuidGetNode->FindPinChecked(FSMNode_Base::GetPathGuidPropertyName());
		
		UEdGraphPin* PathGuidPin = MakeStructNode->FindPinChecked(GET_MEMBER_NAME_CHECKED(FSMProxyPropertyPath, PathGuid));
		ensure(Schema->TryCreateConnection(ValuePin, PathGuidPin));
	}
	
	// Wire old pins to new pins.
	FunctionValuePinOut->CopyPersistentDataFromOldPin(*OldValuePinOut);

	BreakAllNodeLinks();
}

bool USMGraphK2Node_PropertyIOReaderNode::IsConnectedToOwningPropertyNode() const
{
	const USMGraphK2Node_PropertyNode_Base* ConnectedPropertyNode = FSMBlueprintEditorUtils::FindFirstConnectedNode<USMGraphK2Node_PropertyNode_Base>
	(const_cast<USMGraphK2Node_PropertyIOReaderNode*>(this), EGPD_Output);

	return ConnectedPropertyNode != nullptr;
}

UEdGraphPin* USMGraphK2Node_PropertyIOReaderNode::TryGetOwningPropertyNodeRelatedPin() const
{
	if (const USMGraphK2Node_PropertyNode_Base* OwningPropertyNode = GetOwningPropertyNode())
	{
		return OwningPropertyNode->GetResultPin(EGPD_Input);
	}

	return nullptr;
}

bool USMGraphK2Node_PropertyIOReaderNode::IsPropertySelectionPin(const UEdGraphPin* Pin) const
{
	return Pin == GetPropertyPinInChecked();
}

bool USMGraphK2Node_PropertyIOReaderNode::IsPropertyConnectorPin(const UEdGraphPin* Pin) const
{
	return Pin == GetConnectorPinOutChecked();
}

bool USMGraphK2Node_PropertyIOReaderNode::CanDisplayConnectorPin(
	const TSharedPtr<LD::Editor::PropertyUtils::IO::FPropertyData_Base>& InPropertyData, const UEdGraphPin* InPin) const
{
	return InPropertyData && InPropertyData->Property != nullptr;
}

bool USMGraphK2Node_PropertyIOReaderNode::CanAcceptConnection(
	const USMGraphK2Node_PropertyIOBase* OtherPropertyIONode) const
{
	return Super::CanAcceptConnection(OtherPropertyIONode);
}

bool USMGraphK2Node_PropertyIOReaderNode::CanAcceptConnection(
	const USMGraphK2Node_PropertyNode_Base* OtherPropertyNode) const
{
	if (Super::CanAcceptConnection(OtherPropertyNode))
	{
		return OtherPropertyNode->IsOutputProperty();
	}
	return false;
}

TSharedPtr<SWidget> USMGraphK2Node_PropertyIOReaderNode::MakeLinearExpressionNodeWidget() const
{
	const TSharedPtr<LD::Editor::PropertyUtils::IO::FPropertyData_Base> NodeData = GetSelectedNodePropertyData();
	const UEdGraphPin* Pin = GetConnectorPinOutChecked();
	const UEdGraphSchema* Schema = GetGraph()->GetSchema();

	return LD::Editor::PropertyUtils::IO::MakeLinearExpressionNodeWidget(NodeData, Schema);
}

TSharedPtr<SWidget> USMGraphK2Node_PropertyIOReaderNode::MakeLinearExpressionPinWidget(
	const UEdGraphPin* InPin) const
{
	return SNullWidget::NullWidget;
}

TSharedPtr<LD::Editor::PropertyUtils::IO::FPropertyData_Base> USMGraphK2Node_PropertyIOReaderNode::GetSelectedNodePropertyData() const
{
	using namespace LD::Editor::PropertyUtils::IO;

	if (const UEdGraphPin* PropertyPin = GetPropertyPinIn())
	{
		return GetPropertyDataFromPin(PropertyPin);
	}
	return nullptr;
}

UEdGraphPin* USMGraphK2Node_PropertyIOReaderNode::GetPropertyPinIn() const
{
	return FindPin(CreatePropertyPinInName());
}

UEdGraphPin* USMGraphK2Node_PropertyIOReaderNode::GetPropertyPinInChecked() const
{
	return FindPinChecked(CreatePropertyPinInName());
}

UEdGraphPin* USMGraphK2Node_PropertyIOReaderNode::GetConnectorPinOut() const
{
	return FindPin(CreateConnectorPinOutName());
}

UEdGraphPin* USMGraphK2Node_PropertyIOReaderNode::GetConnectorPinOutChecked() const
{
	return FindPinChecked(CreateConnectorPinOutName());
}

FName USMGraphK2Node_PropertyIOReaderNode::CreatePropertyPinInName()
{
	const FName InOutPropertyPinName = "Property";
	return FName(*FString::Printf(TEXT("%s%s"), *GetInputPinPrefix(), *InOutPropertyPinName.ToString()));
}

FName USMGraphK2Node_PropertyIOReaderNode::CreateConnectorPinOutName()
{
	const FName InOutPropertyPinName = "Property";
	return FName(*FString::Printf(TEXT("%s%s"), *GetOutputPinPrefix(), *InOutPropertyPinName.ToString()));
}

