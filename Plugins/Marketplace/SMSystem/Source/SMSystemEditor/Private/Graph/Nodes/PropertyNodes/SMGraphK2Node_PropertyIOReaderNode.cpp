void USMGraphK2Node_PropertyIOReaderNode::AllocateDefaultPins()
{
	Super::AllocateDefaultPins();

	const FName InPinName = CreatePropertyPinInName();
	UEdGraphPin* PropertyPinIn = CreatePin(EGPD_Input, GetPropertySelectionPinIdentifierType(), InPinName);
	SetPropertySelectionPinDefaults(PropertyPinIn);
	
	const FName OutPinName = CreateConnectorPinOutName();
	UEdGraphPin* ConnectorPinOut = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Wildcard, OutPinName);
	SetPropertyConnectorPinDefaults(ConnectorPinOut);
}

void USMGraphK2Node_PropertyIOReaderNode::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	Super::ReallocatePinsDuringReconstruction(OldPins);

	// Make sure custom pins are correct.
	for (UEdGraphPin* Pin : Pins)
	{
		if (IsPropertySelectionPin(Pin))
		{
			if (UEdGraphPin** MatchingOldPin = OldPins.FindByPredicate([Name=Pin->GetFName()](const UEdGraphPin* OldPin)
			{
				return OldPin && OldPin->GetFName() == Name;
			}))
			{
				// Restore output default values.
				Pin->DefaultValue = (*MatchingOldPin)->DefaultValue;
				Pin->DefaultObject = (*MatchingOldPin)->DefaultObject;
				Pin->DefaultTextValue = (*MatchingOldPin)->DefaultTextValue;
				Pin->AutogeneratedDefaultValue = (*MatchingOldPin)->AutogeneratedDefaultValue;
				// Make sure input pin type and visibility is correct.
				UpdatePropertySelectionPin(Pin, false);
			}
		}
	}
}

void USMGraphK2Node_PropertyIOReaderNode::GetMenuActions(FBlueprintActionDatabaseRegistrar& ActionRegistrar) const
{
	const UClass* ActionKey = GetClass();

	if (ActionRegistrar.IsOpenForRegistration(ActionKey))
	{
		UBlueprintNodeSpawner* NodeSpawner = UBlueprintNodeSpawner::Create(GetClass());
		check(NodeSpawner != nullptr);
		ActionRegistrar.AddBlueprintAction(ActionKey, NodeSpawner);
	}
}

bool USMGraphK2Node_PropertyIOReaderNode::IsCompatibleWithGraph(UEdGraph const* Graph) const
{
	return Graph->IsA<USMPropertyGraph>();
}

bool USMGraphK2Node_PropertyIOReaderNode::IsActionFilteredOut(FBlueprintActionFilter const& Filter)
{
	for (UBlueprint* Blueprint : Filter.Context.Blueprints)
	{
		if (!Cast<USMBlueprint>(Blueprint))
		{
			return true;
		}
	}

	// Only list option to create this node if it is not already placed.
	for (const UEdGraph* Graph : Filter.Context.Graphs)
	{
		if (!Graph->IsA<USMPropertyGraph>())
		{
			return true;
		}
	}

	return false;
}

