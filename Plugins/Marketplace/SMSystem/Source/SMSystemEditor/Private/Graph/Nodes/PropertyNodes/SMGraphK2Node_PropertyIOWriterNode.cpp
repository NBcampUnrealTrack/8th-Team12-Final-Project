void USMGraphK2Node_PropertyIOWriterNode::AllocateDefaultPins()
{
	Super::AllocateDefaultPins();
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* PrimaryInputPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Wildcard, CreatePrimaryInputPinName());
	PrimaryInputPin->bDefaultValueIsIgnored = true;
	PrimaryInputPin->PinFriendlyName = LOCTEXT("PrimaryInputPinName", "Proxy Variable");
	PrimaryInputPin->PinToolTip = TEXT("The value provided here will be written to a proxy output for later use by another state.");
	
	for (int32 Idx = 0; Idx < NumOutputs; ++Idx)
	{
		AddConnectorAndSelectionPinsImpl(Idx);
	}
}

void USMGraphK2Node_PropertyIOWriterNode::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	Super::ReallocatePinsDuringReconstruction(OldPins);

	// Make sure custom pins are correct.
	for (UEdGraphPin* Pin : Pins)
	{
		if (IsPropertySelectionPin(Pin))
		{
			if (UEdGraphPin** MatchingOldPin = OldPins.FindByPredicate([Name=Pin->GetFName()](const UEdGraphPin* OldPin)
			{
				return OldPin && OldPin->GetFName() == Name;
			}))
			{
				// Restore output default values.
				Pin->DefaultValue = (*MatchingOldPin)->DefaultValue;
				Pin->DefaultObject = (*MatchingOldPin)->DefaultObject;
				Pin->DefaultTextValue = (*MatchingOldPin)->DefaultTextValue;
				Pin->AutogeneratedDefaultValue = (*MatchingOldPin)->AutogeneratedDefaultValue;
				// Make sure input pin type and visibility is correct.
				UpdatePropertySelectionPin(Pin, false);
			}
		}
		else if (IsPrimaryInputPin(Pin))
		{
			if (UEdGraphPin** MatchingOldPin = OldPins.FindByPredicate([Name=Pin->GetFName()](const UEdGraphPin* OldPin)
			{
				return OldPin && OldPin->GetFName() == Name;
			}))
			{
				Pin->PinType = (*MatchingOldPin)->PinType;
			}
		}
	}
}

