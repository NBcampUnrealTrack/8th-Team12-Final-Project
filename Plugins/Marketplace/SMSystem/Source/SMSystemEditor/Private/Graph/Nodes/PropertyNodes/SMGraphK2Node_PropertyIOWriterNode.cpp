void USMGraphK2Node_PropertyIOWriterNode::PreCompileValidate(FCompilerResultsLog& MessageLog)
{
	if (UEdGraphPin* PrimaryInputPin = GetPrimaryInputPin())
	{
		// Helps cases where the user changed the type of the pin.
		UpdatePrimaryInputPin(PrimaryInputPin);
	}
	
	Super::PreCompileValidate(MessageLog);

	for (const UEdGraphPin* OutputPin : GetAllPropertyOutputs())
	{
		VerifyCorrectPinData(OutputPin, MessageLog);
	}
}

void USMGraphK2Node_PropertyIOWriterNode::CustomExpandNode(FSMKismetCompilerContext& CompilerContext,
                                                               USMGraphK2Node_RuntimeNodeContainer* RuntimeNodeContainer, FProperty* NodeProperty)
{
	using namespace LD::Editor::PropertyUtils::IO;
	
	const USMGraphK2Node_PropertyIOWriterNode* SourceOutputNode =
		CastChecked<USMGraphK2Node_PropertyIOWriterNode>(CompilerContext.MessageLog.FindSourceObject(this));

	if (!SourceOutputNode->IsConnectedToOwningPropertyNode())
	{
		// We're not connected to an owning property node.
		return;
	}
	
	const TSharedPtr<FNodePropertyData> PropertyData = SourceOutputNode->GetOwningPropertyNodePropertyData();
	if (PropertyData->Property == nullptr)
	{
		CompilerContext.MessageLog.Error(TEXT("Owning property is not set for @@."), this);
		return;
	}

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	
	const bool bIsWritingToProxyOutput = IsWritingToProxyOutput();
	const TArray<TTuple<UEdGraphPin*, TSharedPtr<FOwningBlueprintPropertyData>>> BPOutputPins = GetOwningBlueprintOutputPins();

	// All nodes we are adding.
	TArray<UK2Node*> ExpandedNodes;
	ExpandedNodes.Reserve(BPOutputPins.Num() + static_cast<int32>(bIsWritingToProxyOutput));
	
	// Write primary input to proxy variable.
	if (bIsWritingToProxyOutput)
	{
		const UFunction* Function = USMInstance::StaticClass()->FindFunctionByName(TEXT("K2_WriteOutputProperty"));
		check(Function);
	
		UK2Node_CallFunction* WriteOutputFunctionNode = FSMBlueprintEditorUtils::CreateFunctionCall(CompilerContext.ConsolidatedEventGraph, Function);
		CompilerContext.MessageLog.NotifyIntermediateObjectCreation(WriteOutputFunctionNode, this);
	
		UEdGraphPin* FunctionPropertyPathPinIn = WriteOutputFunctionNode->FindPinChecked(FName("PropertyPath"));
		UEdGraphPin* FunctionValuePinIn = WriteOutputFunctionNode->FindPinChecked(FName("Value"));
		const UEdGraphPin* OurValuePinIn = FindPinChecked(CreatePrimaryInputPinName());

		FunctionValuePinIn->PinType = OurValuePinIn->PinType;

		// Create make struct based on owning node property data.
		const UK2Node_MakeStruct* MakeStructNode = MakeAndWirePropertyPathStruct(CompilerContext, PropertyData, FunctionPropertyPathPinIn);
	
		// PathGuid -- requires pin wire since this isn't guaranteed to be known until runtime.
		{
			UK2Node_StructMemberGet* GuidGetNode = CompilerContext.SpawnIntermediateNode<UK2Node_StructMemberGet>(this, CompilerContext.ConsolidatedEventGraph);
			GuidGetNode->VariableReference.SetSelfMember(NodeProperty->GetFName());
			GuidGetNode->StructType = RuntimeNodeContainer->GetRunTimeNodeType();
			GuidGetNode->AllocateDefaultPins();

			// Find the property on FSMNode.
			UEdGraphPin* ValuePin = GuidGetNode->FindPinChecked(FSMNode_Base::GetPathGuidPropertyName());
		
			UEdGraphPin* PathGuidPin = MakeStructNode->FindPinChecked(GET_MEMBER_NAME_CHECKED(FSMProxyPropertyPath, PathGuid));
			ensure(Schema->TryCreateConnection(ValuePin, PathGuidPin));
		}

		// Wire old pins to new pins.
		FunctionValuePinIn->CopyPersistentDataFromOldPin(*OurValuePinIn);

		ExpandedNodes.Add(WriteOutputFunctionNode);
	}

	// If we are writing to owning blueprint pins then we just need to create setters.
	for (const TTuple<UEdGraphPin*, TSharedPtr<FOwningBlueprintPropertyData>>& BPOutputPin : BPOutputPins)
	{
		const UEdGraphPin* OurValueInputPin = FindOppositePin(BPOutputPin.Key);
		check(OurValueInputPin);

		const FProperty* Property = BPOutputPin.Value->Property;
		UClass* PropertyOwnerClass = Cast<UClass>(Property->GetOwnerStruct());
		if (PropertyOwnerClass == nullptr)
		{
			CompilerContext.MessageLog.Error(TEXT("Could not resolve PropertyOwnerClass @@."), this);
			continue;
		}
		
		UK2Node_VariableSet* VarSet = CompilerContext.SpawnIntermediateNode<UK2Node_VariableSet>(this, CompilerContext.ConsolidatedEventGraph);
		VarSet->VariableReference.SetSelfMember(Property->GetFName());
		VarSet->AllocateDefaultPins();

		UEdGraphPin* SetterVariableInputPin = VarSet->FindPinChecked(VarSet->VariableReference.GetMemberName(), EGPD_Input);

		SetterVariableInputPin->CopyPersistentDataFromOldPin(*OurValueInputPin);

		ExpandedNodes.Add(VarSet);
	}

	const UEdGraphPin* OurExecutePinIn = FindPinChecked(UEdGraphSchema_K2::PN_Execute);
	const UEdGraphPin* OurThenPinOut = FindPinChecked(UEdGraphSchema_K2::PN_Then);
	
	if (ExpandedNodes.Num() > 0)
	{
		// Wire all expanded nodes together.
		
		// Replace our execution pin.
		UEdGraphPin* CurrentExecutePin = ExpandedNodes[0]->FindPinChecked(UEdGraphSchema_K2::PN_Execute);
		CurrentExecutePin->CopyPersistentDataFromOldPin(*OurExecutePinIn);

		// Connected our generated nodes.
		for (int32 Idx = 0; Idx < ExpandedNodes.Num() - 1; ++Idx)
		{
			const UK2Node* CurrentNode = ExpandedNodes[Idx];
			const UK2Node* NextNode = ExpandedNodes[Idx + 1];

			UEdGraphPin* CurrentThenPin = CurrentNode->FindPinChecked(UEdGraphSchema_K2::PN_Then);
			UEdGraphPin* NextExecutePin = NextNode->FindPinChecked(UEdGraphSchema_K2::PN_Execute);

			Schema->TryCreateConnection(CurrentThenPin, NextExecutePin);
		}

		// Replace our then pin with the original user execution.
		UEdGraphPin* LastThenPin = ExpandedNodes.Last()->FindPinChecked(UEdGraphSchema_K2::PN_Then);
		LastThenPin->CopyPersistentDataFromOldPin(*OurThenPinOut);
	}
	else if (OurExecutePinIn->LinkedTo.Num() > 0 && OurThenPinOut->LinkedTo.Num() > 0)
	{
		// Handle case where we have no output properties but there is still execution after.
		Schema->TryCreateConnection(OurExecutePinIn->LinkedTo[0], OurThenPinOut->LinkedTo[0]);
	}
	
	BreakAllNodeLinks();
}

UEdGraphPin* USMGraphK2Node_PropertyIOWriterNode::TryGetOwningPropertyNodeRelatedPin() const
{
	if (const USMGraphK2Node_PropertyNode_Base* OwningPropertyNode = GetOwningPropertyNode())
	{
		return OwningPropertyNode->GetResultPin(EGPD_Output);
	}

	return nullptr;
}

bool USMGraphK2Node_PropertyIOWriterNode::IsConnectedToOwningPropertyNode() const
{
	const USMGraphK2Node_PropertyNode_Base* ConnectedPropertyNode = FSMBlueprintEditorUtils::FindFirstConnectedExecNode<USMGraphK2Node_PropertyNode_Base>
	(const_cast<USMGraphK2Node_PropertyIOWriterNode*>(this), EGPD_Input);

	return ConnectedPropertyNode != nullptr;
}

bool USMGraphK2Node_PropertyIOWriterNode::IsPropertySelectionPin(const UEdGraphPin* Pin) const
{
	return Pin
		&& Pin->Direction == EGPD_Output
		&& Pin->GetOwningNode() && Pin->GetOwningNode()->IsA<USMGraphK2Node_PropertyIOWriterNode>()
		&& Pin->PinType.PinCategory != UEdGraphSchema_K2::PC_Exec
		&& Pin->PinType.PinCategory == GetPropertySelectionPinIdentifierType();
}

bool USMGraphK2Node_PropertyIOWriterNode::IsPropertyConnectorPin(const UEdGraphPin* Pin) const
{
	return Pin
		&& Pin->Direction == EGPD_Input
		&& Pin->GetOwningNode() && Pin->GetOwningNode()->IsA<USMGraphK2Node_PropertyIOWriterNode>()
		&& Pin->PinType.PinCategory != UEdGraphSchema_K2::PC_Exec
		&& !IsPrimaryInputPin(Pin);
}

bool USMGraphK2Node_PropertyIOWriterNode::CanDisplayConnectorPin(const TSharedPtr<LD::Editor::PropertyUtils::IO::FPropertyData_Base>& InPropertyData,
	const UEdGraphPin* InPin) const
{
	// Only accept inputs when the output is a variable owned in the sm blueprint, not a state variable.
	return InPropertyData && InPropertyData->PropertyOwnerType == LD::Editor::PropertyUtils::IO::EPropertyOwnerType::OwningBlueprint;
}

