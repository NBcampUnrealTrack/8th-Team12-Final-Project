bool USMGraphK2Node_PropertyIOWriterNode::CanRemoveAllPins() const
{
	return NumOutputs > 0;
}

void USMGraphK2Node_PropertyIOWriterNode::RemoveAllPins()
{
	FScopedTransaction Transaction(LOCTEXT("RemoveAllPins", "Remove All Pins"));
	Modify();
	
	const TArray<UEdGraphPin*> InputOutputPins = GetAllPins();
	for (UEdGraphPin* Pin : InputOutputPins)
	{
		if (IsPropertySelectionPin(Pin))
		{
			RemovePropertyPin(Pin, false);
		}
	}

	NumOutputs = 0;

	TryCreateAvailablePin();

	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(GetBlueprint());
	ReconstructNode();
}

void USMGraphK2Node_PropertyIOWriterNode::RemovePropertyPin(UEdGraphPin* Pin, bool bModify)
{
	FScopedTransaction Transaction(LOCTEXT("RemovePin", "Remove Pin"));
	Modify();

	// Find input and output.
	UEdGraphPin* SourceInputPin = IsPropertyConnectorPin(Pin) ? Pin : FindOppositePin(Pin);
	UEdGraphPin* SourceOutputPin = IsPropertySelectionPin(Pin) ? Pin : FindOppositePin(Pin);

	if (!bProgramaticallySettingPropertyPinValue)
	{
		UEdGraphPin* PropertyPin = IsPropertySelectionPin(SourceInputPin) ? SourceInputPin : SourceOutputPin;
		check(IsPropertySelectionPin(PropertyPin));
		LD::Editor::PropertyUtils::IO::BreakPropertyConnection(PropertyPin);
	}
	else
	{
		// Remove any property references if they exist.
		RemoveReferencedIONode(Pin->PinId);
	}
	
	// Always default to removing the output pin first.
	if (RemovePin(SourceOutputPin))
	{
		if (SourceInputPin)
		{
			SourceInputPin->BreakAllPinLinks();
			ensure(RemovePin(SourceInputPin));
		}
		
		NumOutputs--;
		
		int32 NameIndex = 0;

		// Rename pins after the one removed.
		for (int32 PinIndex = 0; PinIndex < Pins.Num(); ++PinIndex)
		{	
			UEdGraphPin* OutputPin = Pins[PinIndex];
			if (IsPropertySelectionPin(OutputPin))
			{
				// Construct new names for the pins.
				const FName OldOutputPinName = OutputPin->PinName;
				const FName NewOutputPinName = CreateOutputPinName(NameIndex);
				if (NewOutputPinName != OldOutputPinName)
				{
					OutputPin->Modify();
					OutputPin->PinName = NewOutputPinName;
				}

				// Rename the matching input pin.
				if (UEdGraphPin* MatchingInputPin = FindOppositePin(OldOutputPinName))
				{
					const FName NewInputPinName = CreateInputPinName(NameIndex);
					if (NewInputPinName != MatchingInputPin->PinName)
					{
						MatchingInputPin->Modify();
						MatchingInputPin->PinName = NewInputPinName;
					}
				}

				NameIndex++;
			}
		}

		TryCreateAvailablePin();
		
		if (bModify)
		{
			FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(GetBlueprint());
			ReconstructNode();
		}
	}
}

void USMGraphK2Node_PropertyIOWriterNode::UpdatePrimaryInputPin(UEdGraphPin* PrimaryInputPin)
{
	if (IsPrimaryInputPin(PrimaryInputPin))
	{
		if (PrimaryInputPin->LinkedTo.Num() > 0)
		{
			const UEdGraphPin* LinkedToPin = PrimaryInputPin->LinkedTo[0];
			if (PrimaryInputPin->PinType != LinkedToPin->PinType)
			{
				PrimaryInputPin->PinType = LinkedToPin->PinType;
				PinTypeChanged(PrimaryInputPin);
			}
		}
		else if (PrimaryInputPin->PinType.PinCategory != UEdGraphSchema_K2::PC_Wildcard)
		{
			PrimaryInputPin->PinType.PinCategory = UEdGraphSchema_K2::PC_Wildcard;
			PinTypeChanged(PrimaryInputPin);
		}
	}
}

UEdGraphPin* USMGraphK2Node_PropertyIOWriterNode::FindOrAddAndSetPropertyPinForPropertyData(
	const TSharedPtr<LD::Editor::PropertyUtils::IO::FPropertyData_Base>& InPropertyData)
{
	using namespace LD::Editor::PropertyUtils::IO;
	UEdGraphPin* EmptyPin = nullptr;
	const TArray<UEdGraphPin*> Outputs = GetAllPropertyOutputs();
	for (UEdGraphPin* Pin : Outputs)
	{
		if (TSharedPtr<FPropertyData_Base> PropertyData = GetPropertyDataFromPin(Pin))
		{
			if (*PropertyData == *InPropertyData)
			{
				return Pin;
			}
		}
		else
		{
			EmptyPin = Pin;
		}
	}

	// Use either an empty pin or create a new one.
	UEdGraphPin* PinToSet = EmptyPin ? EmptyPin : CreateConnectorPin();
	if (ensure(PinToSet))
	{
		SetPropertySelectionPinValue(PinToSet, InPropertyData);
	}
	return PinToSet;
}

void USMGraphK2Node_PropertyIOWriterNode::ClearOrRemovePropertyPinForPropertyData(
	const TSharedPtr<LD::Editor::PropertyUtils::IO::FPropertyData_Base>& InPropertyData)
{
	using namespace LD::Editor::PropertyUtils::IO;
	IterateOutputs:
	const TArray<UEdGraphPin*> Outputs = GetAllPropertyOutputs();
	for (UEdGraphPin* Pin : Outputs)
	{
		if (TSharedPtr<FPropertyData_Base> PropertyData = GetPropertyDataFromPin(Pin))
		{
			if (*PropertyData == *InPropertyData)
			{
				if (GetNumOutputs() > 1)
				{
					TGuardValue SetPinValueGuard(bProgramaticallySettingPropertyPinValue, true);
					RemoveInputPin(Pin);
					// We restart the loop because this can trigger a refresh of all pins, and our current pins
					// are invalidated. In almost every case there should be only "one" matching pin, but we should
					// iterate again to make sure. We could potentially look up the new pin from the guid, but I don't 
					// trust the old pin objects to be valid, and performance isn't critical for this operation.
					goto IterateOutputs;
				}
				else
				{
					SetPropertySelectionPinValue(Pin, nullptr);
				}
			}
		}
	}
}

UEdGraphPin* USMGraphK2Node_PropertyIOWriterNode::GetPrimaryInputPin() const
{
	for (UEdGraphPin* Pin : Pins)
	{
		if (IsPrimaryInputPin(Pin))
		{
			return Pin;
		}
	}

	return nullptr;
}

UEdGraphPin* USMGraphK2Node_PropertyIOWriterNode::AddConnectorAndSelectionPinsImpl(int32 InIndex)
{
	const FName InPinName = CreateInputPinName(InIndex);
	UEdGraphPin* InPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Wildcard, InPinName);
	SetPropertyConnectorPinDefaults(InPin);
	
	const FName OutPinName = CreateOutputPinName(InIndex);
	UEdGraphPin* OutPin = CreatePin(EGPD_Output, GetPropertySelectionPinIdentifierType(), OutPinName);
	SetPropertySelectionPinDefaults(OutPin);
	return OutPin;
}

void USMGraphK2Node_PropertyIOWriterNode::TryCreateAvailablePin()
{
	bool bNeedsPin = NumOutputs == 0;

	if (!bNeedsPin && CanAddPin())
	{
		bNeedsPin = true;
		for (const UEdGraphPin* Pin : GetAllPropertyOutputs())
		{
			if (Pin->IsDefaultAsStringEmpty())
			{
				bNeedsPin = false;
				break;
			}
		}
	}

	if (bNeedsPin)
	{
		AddInputPin();
	}
}

FName USMGraphK2Node_PropertyIOWriterNode::CreateInputPinName(int32 InNameIndex) const
{
	return FName(*FString::Printf(TEXT("%s%s"), *GetInputPinPrefix(),
			*GetNameForAdditionalPin(InNameIndex).ToString()));
}

FName USMGraphK2Node_PropertyIOWriterNode::CreateOutputPinName(int32 InNameIndex) const
{
	return FName(*FString::Printf(TEXT("%s%s"), *GetOutputPinPrefix(),
			*GetNameForAdditionalPin(InNameIndex).ToString()));
}

FName USMGraphK2Node_PropertyIOWriterNode::CreatePrimaryInputPinName()
{
	return FName("PrimaryInput");
}

bool USMGraphK2Node_PropertyIOWriterNode::IsPrimaryInputPin(const UEdGraphPin* Pin)
{
	return Pin && Pin->GetFName() == CreatePrimaryInputPinName();
}

bool USMGraphK2Node_PropertyIOWriterNode::IsWritingToProxyOutput() const
{
	using namespace LD::Editor::PropertyUtils::IO;
	for (const UEdGraphPin* Pin : Pins)
	{
		if (IsPropertySelectionPin(Pin))
		{
			if (const TSharedPtr<FPropertyData_Base> PropertyData = GetPropertyDataFromPin(Pin))
			{
				if (PropertyData->IsA<FNodePropertyData>())
				{
					return true;
				}
			}
		}
	}
	
	return false;
}

TArray<TTuple<UEdGraphPin*,
	TSharedPtr<LD::Editor::PropertyUtils::IO::FOwningBlueprintPropertyData>>> USMGraphK2Node_PropertyIOWriterNode::GetOwningBlueprintOutputPins() const
{
	using namespace LD::Editor::PropertyUtils::IO;
	
	TArray<TTuple<UEdGraphPin*, TSharedPtr<FOwningBlueprintPropertyData>>> OutputPins;
	
	for (UEdGraphPin* Pin : Pins)
	{
		if (IsPropertySelectionPin(Pin))
		{
			if (const TSharedPtr<FPropertyData_Base> PropertyData = GetPropertyDataFromPin(Pin))
			{
				if (const TSharedPtr<FOwningBlueprintPropertyData> NodePropertyData
					= PropertyData->As<FOwningBlueprintPropertyData>())
				{
					OutputPins.Add({ Pin, NodePropertyData });
				}
			}
		}
	}

	return OutputPins;
}

TArray<UEdGraphPin*> USMGraphK2Node_PropertyIOWriterNode::GetAllPropertyOutputs() const
{
	TArray<UEdGraphPin*> OutputPins;
	OutputPins.Reserve(NumOutputs);

	for (UEdGraphPin* Pin : Pins)
	{
		if (IsPropertySelectionPin(Pin))
		{
			OutputPins.Add(Pin);
		}
	}

	return OutputPins;
}

UEdGraphPin* USMGraphK2Node_PropertyIOWriterNode::CreateConnectorPin()
{
	UEdGraphPin* OutputPin = nullptr;
	if (CanAddPin())
	{
		FScopedTransaction Transaction(LOCTEXT("AddPin", "Add Pin"), !GIsTransacting);
		Modify();

		OutputPin = AddConnectorAndSelectionPinsImpl(NumOutputs);
		
		NumOutputs++;
	
		FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(GetBlueprint());
	}

	return OutputPin;
}

