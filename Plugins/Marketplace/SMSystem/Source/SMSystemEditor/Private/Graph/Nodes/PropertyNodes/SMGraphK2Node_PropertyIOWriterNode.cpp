bool USMGraphK2Node_PropertyIOWriterNode::IsActionFilteredOut(FBlueprintActionFilter const& Filter)
{
	for (UBlueprint* Blueprint : Filter.Context.Blueprints)
	{
		if (!Cast<USMBlueprint>(Blueprint))
		{
			return true;
		}
	}

	// Only list option to create this node if it is not already placed.
	for (const UEdGraph* Graph : Filter.Context.Graphs)
	{
		if (!Graph->IsA<USMPropertyGraph>()
			|| (Graph->IsA<USMPropertyGraph>() && FSMBlueprintEditorUtils::IsNodeAlreadyPlaced<USMGraphK2Node_PropertyIOWriterNode>(Graph)))
		{
			return true;
		}
	}

	return false;
}

