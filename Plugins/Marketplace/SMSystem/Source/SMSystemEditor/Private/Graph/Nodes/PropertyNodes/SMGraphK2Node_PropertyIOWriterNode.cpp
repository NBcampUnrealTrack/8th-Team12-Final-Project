bool USMGraphK2Node_PropertyIOWriterNode::CanUserDeleteNode() const
{
	if (const USMGraphK2Node_PropertyNode_Base* OwningProperty = GetOwningPropertyNode())
	{
		// Don't allow deletion if this is correctly hooked up to an output property, this is required!
		return !OwningProperty->IsOutputProperty();
	}
	
	return true;
}

